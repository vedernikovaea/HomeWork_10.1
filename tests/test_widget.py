from src.widget import mask_account_card
import pytest


@pytest.mark.parametrize("input_data,expected", [
    # 16-значные номера (карты)
    ("1234567812345678", "1234 56** **** 5678"),
    ("1234 5678 1234 5678", "1234 56** **** 5678"),
    ("Visa 1234567812345678", "Visa 1234 56** **** 5678"),
    ("MasterCard 1234 5678 1234 5678", "MasterCard 1234 56** **** 5678"),
    ("МИР 1234567812345678", "МИР 1234 56** **** 5678"),
    ("Visa Classic 1234567812345678", "Visa Classic 1234 56** **** 5678"),

    # 20-значные номера (счета)
    ("Счет 12345678901234567890", "Счет **7890"),
    ("12345678901234567890", "Счет **7890"),
    ("Счет  12345678901234567890", "Счет **7890"),
    ("40817810099912345678", "Счет **5678"),
    ("40817.810.0.999.12345678", "Счет **5678"),
    ("Расчетный счет 12345678901234567890", "Счет **7890"),

    # Некорректные данные
    ("", "Введите корректный номер Вашей карты или счета"),
    ("12345678", "Введите корректный номер Вашей карты или счета"),
    ("123456781234", "Введите корректный номер Вашей карты или счета"),
    ("123456781234567", "Введите корректный номер Вашей карты или счета"),  # 15 цифр
    ("12345678123456789", "Введите корректный номер Вашей карты или счета"),  # 17 цифр
    ("123456781234567890123", "Введите корректный номер Вашей карты или счета"),  # 21 цифра
    ("Карта 12345678", "Введите корректный номер Вашей карты или счета"),
    ("Счет 12345678", "Введите корректный номер Вашей карты или счета"),

    # Смешанные символы
    ("Visa 1234-5678-1234-5678", "Visa 1234 56** **** 5678"),
    ("MC 1234 5678 1234 5678 9012", "MC **9012"),  # 20 цифр с префиксом
    ("ABC1234567812345678DEF", "ABC1234 56** **** 5678DEF"),  # символы вокруг
])
def test_mask_account_card(input_data, expected):
    """Тестирование различных входных данных для карт и счетов"""
    assert mask_account_card(input_data) == expected


@pytest.mark.parametrize("input_data,expected", [
    # Граничные случаи для карт
    ("0000000000000000", "0000 00** **** 0000"),
    ("9999999999999999", "9999 99** **** 9999"),

    # Граничные случаи для счетов
    ("00000000000000000000", "Счет **0000"),
    ("99999999999999999999", "Счет **9999"),

    # Карты с разными разделителями
    ("1234-5678-1234-5678", "1234 56** **** 5678"),
    ("1234.5678.1234.5678", "1234 56** **** 5678"),
    ("1234 5678  1234  5678", "1234 56** **** 5678"),

    # Счета с разными разделителями
    ("1234-5678-9012-3456-7890", "Счет **7890"),
    ("1234 5678 9012 3456 7890", "Счет **7890"),
    ("1234.5678.9012.3456.7890", "Счет **7890"),
])
def test_mask_account_card_edge_cases(input_data, expected):
    """Тестирование граничных случаев и разных форматов ввода"""
    assert mask_account_card(input_data) == expected