import pytest

from src.masks import mask_account


@pytest.mark.parametrize("account,expected", [
    # Короткие номера без пробелов
    ("1234567890123456789", "Ошибка: нужен 20-значный номер счета"),  # 19 цифр
    ("123", "Ошибка: нужен 20-значный номер счета"),  # 3 цифры
    ("", "Ошибка: нужен 20-значный номер счета"),  # пустая строка

    # Короткие номера с пробелами
    ("1234 5678 9012 3456 78", "Ошибка: нужен 20-значный номер счета"),  # 18 цифр с пробелами
    ("12 34 56", "Ошибка: нужен 20-значный номер счета"),  # 6 цифр с пробелами

    # Короткие номера с буквами
    ("12345678901234567AB", "Ошибка: нужен 20-значный номер счета"),  # 19 символов, последние 2 - буквы
    ("ABC", "Ошибка: нужен 20-значный номер счета"),  # только буквы
])
def test_short_accounts(account, expected):
    """Параметризованный тест для различных коротких номеров счетов"""
    result = mask_account(account)
    assert result == expected, f"Для счета '{account}' ожидалось '{expected}', получено '{result}'"
