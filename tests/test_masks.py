import pytest

from src.masks import mask_card


@pytest.mark.parametrize("input_card,expected", [
    # Валидные номера карт
    ("1234567812345678", "1234 56** **** 5678"),
    ("1234 5678 1234 5678", "1234 56** **** 5678"),
    ("  1234567812345678  ", "1234 56** **** 5678"),

    # Невалидные номера карт
    ("12345678", "Ошибка: нужен 16-значный номер карты"),
    ("12345678123456781234", "Ошибка: нужен 16-значный номер карты"),
    ("abcd567812345678", "Ошибка: нужен 16-значный номер карты"),
    ("1234-5678-1234-5678", "Ошибка: нужен 16-значный номер карты"),
    ("", "Ошибка: нужен 16-значный номер карты"),
    ("1234 5678 1234", "Ошибка: нужен 16-значный номер карты"),

    # Граничные случаи
    ("0000000000000000", "0000 00** **** 0000"),
    ("9999999999999999", "9999 99** **** 9999"),
])
def test_mask_card_various_inputs(input_card, expected):
    """Тестирование различных входных данных"""
    assert mask_card(input_card) == expected
